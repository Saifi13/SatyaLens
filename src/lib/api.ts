import type { VerifyEvent, VerificationReport } from "../types";

export class ApiError extends Error {
  constructor(
    message: string,
    readonly code = "API_ERROR"
  ) {
    super(message);
  }
}

export interface HealthInfo {
  configured: boolean;
  missing: string[];
  searchProvider: string;
  aiModel: string | null;
}

const API_BASE = (import.meta.env.VITE_API_BASE_URL ?? "").replace(/\/+$/, "");

function apiUrl(path: string): string {
  return `${API_BASE}${path}`;
}

export async function fetchHealth(): Promise<HealthInfo> {
  const res = await fetch(apiUrl("/api/health"));
  if (!res.ok) throw new ApiError("Verification service is unreachable.", "OFFLINE");
  return res.json();
}

export async function runVerification(
  claim: string,
  onEvent: (e: VerifyEvent) => void,
  signal: AbortSignal
): Promise<void> {
  let res: Response;
  try {
    res = await fetch(apiUrl("/api/verify"), {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ claim }),
      signal,
    });
  } catch (err) {
    if ((err as Error).name === "AbortError") throw err;
    throw new ApiError(
      "Could not reach the verification service. Is the server running?",
      "OFFLINE"
    );
  }
  if (!res.ok) {
    let payload: { error?: string; message?: string } = {};
    try {
      payload = await res.json();
    } catch {
      /* fall through with generic message */
    }
    throw new ApiError(
      payload.message ?? `Verification request failed (HTTP ${res.status}).`,
      payload.error ?? "HTTP"
    );
  }
  const reader = res.body?.getReader();
  if (!reader) throw new ApiError("The verification stream could not be opened.");
  const decoder = new TextDecoder();
  let buffer = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    let sep: number;
    while ((sep = buffer.indexOf("\n\n")) !== -1) {
      const frame = buffer.slice(0, sep);
      buffer = buffer.slice(sep + 2);
      for (const line of frame.split("\n")) {
        if (!line.startsWith("data:")) continue;
        const payload = line.slice(5).trim();
        if (!payload || payload === "[DONE]") continue;
        try {
          onEvent(JSON.parse(payload) as VerifyEvent);
        } catch {
          /* ignore malformed keepalive frames */
        }
      }
    }
  }
}

export function reportToMarkdown(r: VerificationReport): string {
  const lines: string[] = [
    `# SatyaLens verification report`,
    ``,
    `**Claim:** ${r.claim}`,
    `**Verdict:** ${r.verdict} (confidence: ${r.confidence})`,
    `**Verified at:** ${new Date(r.verifiedAt).toUTCString()}`,
    ``,
    `## Summary`,
    r.summary,
    ``,
    `## Sub-claims`,
  ];
  for (const s of r.subClaims) {
    lines.push(
      ``,
      `- ${s.text}`,
      `  - Verdict: ${s.verdict ?? "n/a"} — ${s.explanation}`
    );
  }
  lines.push(``, `## Sources`);
  r.sources.forEach((s, i) => {
    lines.push(`${i + 1}. [${s.title}](${s.url}) — ${s.publisher}${s.publishedAt ? `, ${s.publishedAt}` : ""} (${s.category})${s.accessed ? "" : " [snippet only]"}`);
  });
  lines.push(``, `## Assessment`, r.assessment.rationale);
  lines.push(``, `## Limitations`, r.limitations);
  lines.push(``, `_Generated by SatyaLens. Open every source and verify for yourself._`);
  return lines.join("\n");
}
